#!/usr/bin/env python3
"""Generate crates/emoji/src/table.rs from Unicode emoji data.

Usage: python3 -I crates/emoji/gen/gen.py [emoji-test.txt [annotations.json]]

With no arguments both files are downloaded (stdlib urllib). The output is
checked in, so building the crate never touches the network.

Sources:
  https://unicode.org/Public/emoji/latest/emoji-test.txt
  https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/
      cldr-annotations-full/annotations/en/annotations.json
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

EMOJI_TEST_URL = "https://unicode.org/Public/emoji/latest/emoji-test.txt"
ANNOTATIONS_URL = (
    "https://raw.githubusercontent.com/unicode-org/cldr-json/main/cldr-json/"
    "cldr-annotations-full/annotations/en/annotations.json"
)
OUT = Path(__file__).resolve().parent.parent / "src" / "table.rs"

# emoji-test.txt group name -> Category variant. "Component" is skipped.
CATEGORIES = {
    "Smileys & Emotion": "SmileysEmotion",
    "People & Body": "PeopleBody",
    "Animals & Nature": "AnimalsNature",
    "Food & Drink": "FoodDrink",
    "Travel & Places": "TravelPlaces",
    "Activities": "Activities",
    "Objects": "Objects",
    "Symbols": "Symbols",
    "Flags": "Flags",
}

VS16 = 0xFE0F
TONE1 = 0x1F3FB


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read().decode("utf-8")


def read_or_fetch(args, i, url):
    if len(args) > i:
        return Path(args[i]).read_text(encoding="utf-8")
    return fetch(url)


def rust_str(s):
    return json.dumps(s, ensure_ascii=False)


def rust_char_str(cps):
    return '"' + "".join("\\u{%X}" % c for c in cps) + '"'


def words(s):
    return [w for w in re.split(r"[^\w+]+", s.lower()) if w]


def main():
    args = sys.argv[1:]
    text = read_or_fetch(args, 0, EMOJI_TEST_URL)
    annotations = json.loads(read_or_fetch(args, 1, ANNOTATIONS_URL))["annotations"][
        "annotations"
    ]

    version = date = ""
    group = None
    rows = []  # (cps, name, group)
    tone_rows = set()
    for line in text.splitlines():
        if line.startswith("# Version:"):
            version = line.split(":", 1)[1].strip()
        elif line.startswith("# Date:"):
            date = line.split(":", 1)[1].strip()
        elif line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
        if not line or line.startswith("#"):
            continue
        left, right = line.split(";", 1)
        status, comment = right.split("#", 1)
        if status.strip() != "fully-qualified" or group not in CATEGORIES:
            continue
        cps = tuple(int(x, 16) for x in left.split())
        # comment: " <emoji> E<ver> <name>"
        name = comment.strip().split(" ", 2)[2]
        if "skin tone" in name:
            tone_rows.add(cps)
        else:
            rows.append((cps, name, group))

    def tone_candidate(cps):
        # The single-tone variant: tone right after the base codepoint, with
        # the now-redundant emoji presentation selector dropped.
        rest = cps[1:]
        if rest and rest[0] == VS16:
            rest = rest[1:]
        return (cps[0], TONE1) + rest

    out = []
    for cps, name, group in rows:
        ch = "".join(map(chr, cps))
        ann = annotations.get(ch) or annotations.get(ch.replace("️", "")) or {}
        kws = []
        for w in words(name) + [k.lower() for k in ann.get("default", [])]:
            if w not in kws:
                kws.append(w)
        tones = tone_candidate(cps) in tone_rows
        out.append(
            "    Emoji { ch: %s, name: %s, keywords: &[%s], category: Category::%s, skin_tones: %s },"
            % (
                rust_char_str(cps),
                rust_str(name),
                ", ".join(rust_str(k) for k in kws),
                CATEGORIES[group],
                "true" if tones else "false",
            )
        )

    header = f"""\
// @generated by crates/emoji/gen/gen.py -- do not edit by hand.
//
// Source: {EMOJI_TEST_URL}
//         (Emoji Keyboard/Display Test Data for UTS #51, Version {version}, {date})
// Keywords: CLDR English annotations (unicode-org/cldr-json) plus name words.
//
// Data (c) Unicode, Inc. Distributed under the Unicode License v3,
// https://www.unicode.org/terms_of_use.html
//
// Regenerate: python3 -I crates/emoji/gen/gen.py

use crate::{{Category, Emoji}};

#[rustfmt::skip]
pub(crate) static EMOJI: &[Emoji] = &[
"""
    OUT.write_text(header + "\n".join(out) + "\n];\n", encoding="utf-8")
    print(f"wrote {len(out)} emoji to {OUT}")


main()
